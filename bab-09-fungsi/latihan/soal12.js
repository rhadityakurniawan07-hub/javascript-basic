// Challenge Kalkulator
function tambah(a, b) {
  return a + b;
}

function kurang(a, b) {
  return a - b;
}

function kali(a, b) {
  return a * b;
}
function bagi(a, b) {
  return a / b;
}

console.log("Tambah :", tambah(10, 5));
console.log("Kurang :", kurang(10, 5));
console.log("Kali   :", kali(10, 5));
console.log("Bagi   :", bagi(10, 5));