// Iterable atau Non-Iterable
/*
1. "Indonesia" → Iterable, karena String dapat diulang setiap karakternya.
2. ["Merah", "Putih"] → Iterable, karena Array dapat diulang setiap elemennya.
3. 150 → Non-Iterable, karena Number tidak dapat diulang.
4. true → Non-Iterable, karena Boolean tidak dapat diulang.
5. { nama: "Budi" } → Non-Iterable, karena Object biasa tidak dapat langsung diulang dengan for...of.
*/